export function isMastodonUsername(value: string): boolean {
  return /^@[a-zA-Z0-9_-]+@[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}$/.test(value);
}

export function mastodonToUrl(username: string): string {
  const match = username.match(/^@([a-zA-Z0-9_-]+)@([a-zA-Z0-9.-]+\.[a-zA-Z]{2,})$/);
  if (match) {
    return `https://${match[2]}/@${match[1]}`;
  }
  return username;
}

export function getSocialPlatform(url: string): SocialPlatform {
  if (isMastodonUsername(url)) {
    return { name: "Mastodon", icon: <MastodonIcon />, color: "#6364ff" };
  }
  for (const { pattern, platform } of platformPatterns) {
    if (pattern.test(url)) {
      return platform;
    }
  }
  return { name: "Link", icon: <LinkIcon />, color: "var(--color-text-muted)" };
}
